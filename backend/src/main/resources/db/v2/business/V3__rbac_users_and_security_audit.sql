-- Existing V1 test/account tooling inserts a fixed role; provide a transactional compatibility association.
-- V2 user management replaces this initial association with the explicitly authorized role set before commit.
create function public.bridge_inserted_v1_role() returns trigger language plpgsql as $$
begin
 insert into public.sys_user_role(user_id,role_id) select new.id,id from public.sys_role where code=new.role;
 return new;
end $$;
create trigger associate_v1_role after insert on public.sys_user for each row execute function public.bridge_inserted_v1_role();
