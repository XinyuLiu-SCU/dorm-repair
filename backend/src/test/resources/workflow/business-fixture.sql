-- test database only; no production data copied.
create table if not exists sys_user (
 id bigint generated by default as identity primary key,
 username varchar(50) not null unique, password_hash varchar(255) not null,
 real_name varchar(50) not null, role varchar(20) not null check (role in ('STUDENT','REPAIRER','ADMIN')),
 phone varchar(20), created_at timestamp not null default current_timestamp
);
create table if not exists repair_order (
 id bigint generated by default as identity primary key,
 student_id bigint not null references sys_user(id), repairer_id bigint references sys_user(id),
 title varchar(100) not null, description text not null, location varchar(200) not null,
 status varchar(30) not null default 'PENDING' check (status in ('PENDING','APPROVED','REJECTED','ASSIGNED','IN_PROGRESS','WAITING_ACCEPTANCE','REWORK','COMPLETED')),
 created_at timestamp not null default current_timestamp, updated_at timestamp not null default current_timestamp
);
create table if not exists repair_record (
 id bigint generated by default as identity primary key, order_id bigint not null references repair_order(id),
 repairer_id bigint not null references sys_user(id), description text not null, created_at timestamp not null default current_timestamp
);
